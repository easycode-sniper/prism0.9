/** What lands in the "N° carte unique" column when nothing matches. */
export const CARD_NOT_FOUND = "not found";

/**
 * Normalises a raw card cell exactly the way the standalone tool did —
 * trim, then strip whitespace, zero-width characters and quotes — before
 * the lookup, because the sheet paste carries all three. Null when the
 * card is unknown; the pipeline decides what the export shows for one.
 */
export function lookupCard(raw: unknown): CardEntry | null {
  const normalised = (raw?.toString().trim() ?? "").replace(/[\s\u200B-\u200D\uFEFF'"]/g, "");
  return CARD_MAPPING[normalised] ?? null;
}
