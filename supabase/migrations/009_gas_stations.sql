-- ━─ Gas stations ━──────────────────────────────────────
-- Real station list supplied by the operator (name + coordinates).
-- Rows with no coordinates in the source list are omitted — there is
-- nothing to plot or do proximity checks against without a position.

CREATE TABLE IF NOT EXISTS public.gas_stations (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name        TEXT NOT NULL,
  lat         DOUBLE PRECISION NOT NULL,
  lng         DOUBLE PRECISION NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.gas_stations ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Gas stations viewable by authenticated users"
  ON public.gas_stations FOR SELECT TO authenticated USING (true);

